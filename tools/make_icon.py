"""Eddy's app icon: a download arrow coming down onto water: a wave, and a
fainter, shorter one below it (the wave under the Eddy wordmark).

    python3 tools/make_icon.py <out dir>

writes ic_launcher_foreground.xml and ic_launcher_monochrome.xml (Android's
adaptive icon, on ic_launcher_background's blue) and logo.svg (desktop).
The drawing is white strokes (the lower wave at 60%), the same in all
three; the themed (one colour) icon has the system pick their colour.
"""
import sys

OUT = sys.argv[1]


def wave(x0, x1, y, amp, crests):
    """A sine wave from x0 to x1 about y, as one cubic per half period."""
    halves = round(crests * 2)
    step = (x1 - x0) / halves
    d = f"M{x0:g} {y:g}"
    for i in range(halves):
        x = x0 + i * step
        peak = y + (-amp if i % 2 == 0 else amp) * 4 / 3
        d += f" C{x + step * 0.36:.2f} {peak:.2f} {x + step * 0.64:.2f} {peak:.2f} {x + step:.2f} {y:g}"
    return d


# On the 108 grid.
ARROW = "M54 18 V56 M38 42 L54 58 L70 42"
WAVE = wave(22, 86, 74, 3, 3)
RIPPLE = wave(30, 78, 88, 2.6, 2)
ARROW_WIDTH, WAVE_WIDTH, RIPPLE_WIDTH = 10, 6.5, 6
RIPPLE_ALPHA = 0.6
BG = ("#FF4F8DF7", "#FF2447C9")  # ic_launcher_background's gradient
# Adaptive icons are cropped to (at least) a 66dp circle: the drawing is
# scaled about the centre to stay in it.
SAFE_SCALE = 0.68


def group(body):
    return f'''    <!-- Scaled about the centre to stay inside the 66dp safe zone. -->
    <group
        android:pivotX="54"
        android:pivotY="54"
        android:scaleX="{SAFE_SCALE}"
        android:scaleY="{SAFE_SCALE}">
{body}
    </group>'''


def stroke(path, width, color, alpha=1.0):
    return f'''        <path
            android:pathData="{path}"
            android:strokeWidth="{width:g}"
            android:strokeColor="{color}"
            android:strokeAlpha="{alpha:g}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />'''


def vector(comment, body):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tools/make_icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">

{group(body)}
</vector>
'''


strokes = "\n".join([
    stroke(ARROW, ARROW_WIDTH, "#FFFFFFFF"),
    stroke(WAVE, WAVE_WIDTH, "#FFFFFFFF"),
    stroke(RIPPLE, RIPPLE_WIDTH, "#FFFFFFFF", RIPPLE_ALPHA),
])
open(f"{OUT}/ic_launcher_foreground.xml", "w").write(
    vector("Launcher icon: a download arrow coming down onto water.", strokes)
)
open(f"{OUT}/ic_launcher_monochrome.xml", "w").write(
    vector("Themed (monochrome) launcher icon: the same strokes; the system picks the colour.", strokes)
)

argb = lambda c: "#" + c[3:]
open(f"{OUT}/logo.svg", "w").write(f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">
  <!-- Eddy's icon: a download arrow coming down onto water. Generated by
       tools/make_icon.py. -->
  <defs>
    <linearGradient id="bg" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="{argb(BG[0])}" />
      <stop offset="100%" stop-color="{argb(BG[1])}" />
    </linearGradient>
  </defs>
  <rect width="108" height="108" rx="24" fill="url(#bg)" />
  <g transform="translate(54 54) scale({SAFE_SCALE}) translate(-54 -54)" fill="none" stroke="#FFFFFF" stroke-linecap="round" stroke-linejoin="round">
    <path d="{ARROW}" stroke-width="{ARROW_WIDTH}" />
    <path d="{WAVE}" stroke-width="{WAVE_WIDTH}" />
    <path d="{RIPPLE}" stroke-width="{RIPPLE_WIDTH}" stroke-opacity="{RIPPLE_ALPHA}" />
  </g>
</svg>
''')
print("ok")
